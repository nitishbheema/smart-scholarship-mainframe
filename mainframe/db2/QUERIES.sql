-- Q1: Fetch Eligible Students with Full Academic and Bank Details for Disbursement
SELECT 
    E.APP_ID,
    E.STU_ID,
    S.FIRST_NAME || ' ' || S.LAST_NAME AS FULL_NAME,
    S.DEPARTMENT,
    E.CGPA,
    E.ATTENDANCE_PCT,
    E.FAMILY_INCOME,
    E.AWARD_AMOUNT,
    A.BANK_AC_NUM,
    A.BANK_IFSC,
    E.BATCH_ID
FROM ELIGIBILITY_RESULT E
JOIN STUDENT_MASTER S ON E.STU_ID = S.STU_ID
JOIN SCHOLARSHIP_APPLICATION A ON E.APP_ID = A.APP_ID
WHERE E.STATUS = 'E'
ORDER BY E.AWARD_AMOUNT DESC, E.CGPA DESC;

-- Q2: Summary of Applications by Status and Total Financial Obligation
SELECT 
    STATUS,
    COUNT(*) AS TOTAL_APPLICATIONS,
    COALESCE(SUM(AWARD_AMOUNT), 0) AS TOTAL_SCHOLARSHIP_INR,
    AVG(CGPA) AS AVG_CGPA,
    AVG(ATTENDANCE_PCT) AS AVG_ATTENDANCE
FROM ELIGIBILITY_RESULT
GROUP BY STATUS;

-- Q3: Rejection Breakdown Analysis (Pareto Distribution)
SELECT 
    REASON_CODE,
    COUNT(*) AS REJECTION_COUNT,
    ROUND((COUNT(*) * 100.0) / (SELECT COUNT(*) FROM ELIGIBILITY_RESULT WHERE STATUS = 'R'), 2) AS REJ_PERCENTAGE
FROM ELIGIBILITY_RESULT
WHERE STATUS = 'R'
GROUP BY REASON_CODE
ORDER BY REJECTION_COUNT DESC;

-- Q4: Disbursement Status & Bank Advice Reconciliation
SELECT 
    D.BATCH_ID,
    D.STATUS AS DISBURSEMENT_STATUS,
    COUNT(D.DISB_REF_ID) AS PAYMENT_COUNT,
    SUM(D.AMOUNT) AS TOTAL_DISBURSED_AMOUNT,
    MIN(D.VALUE_DATE) AS EARLIEST_VALUE_DATE,
    MAX(D.VALUE_DATE) AS LATEST_VALUE_DATE
FROM DISBURSEMENT_RECORD D
GROUP BY D.BATCH_ID, D.STATUS;

-- Q5: Duplicate Application Detection Cross-Check
SELECT 
    STU_ID,
    SCH_CODE,
    COUNT(*) AS APPLICATION_COUNT
FROM SCHOLARSHIP_APPLICATION
GROUP BY STU_ID, SCH_CODE
HAVING COUNT(*) > 1;

-- Q6: Batch Processing Execution Audit History
SELECT 
    BATCH_ID,
    JOB_NAME,
    RECS_READ,
    RECS_VALID,
    RECS_ELIGIBLE,
    RECS_REJECTED,
    RECS_DUPLICATE,
    TOTAL_DISBURSED_AMT,
    RETURN_CODE,
    START_TS,
    END_TS,
    ROUND((TIMESTAMPDIFF(2, CHAR(END_TS - START_TS))), 2) AS DURATION_SECS
FROM PROCESSING_AUDIT
ORDER BY START_TS DESC;
