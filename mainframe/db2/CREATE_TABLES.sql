-- 1. SCHOLARSHIP MASTER TABLE
CREATE TABLE SCHOLARSHIP_MASTER (
    SCH_CODE            CHAR(6)         NOT NULL,
    SCH_NAME            VARCHAR(60)     NOT NULL,
    SCH_DESC            VARCHAR(255),
    MIN_CGPA            DECIMAL(4,2)    NOT NULL DEFAULT 7.50,
    MIN_ATTENDANCE      DECIMAL(5,2)    NOT NULL DEFAULT 75.00,
    MAX_ANNUAL_INCOME   DECIMAL(10,2)   NOT NULL DEFAULT 250000.00,
    MAX_ACTIVE_ARREARS  SMALLINT        NOT NULL DEFAULT 0,
    IS_ACTIVE           CHAR(1)         NOT NULL DEFAULT 'Y',
    CREATED_TS          TIMESTAMP       NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_SCHOLARSHIP_MSTR PRIMARY KEY (SCH_CODE),
    CONSTRAINT CK_SCH_ACTIVE CHECK (IS_ACTIVE IN ('Y', 'N'))
);

-- 2. STUDENT MASTER TABLE (Db2 RELATIONAL STORE)
CREATE TABLE STUDENT_MASTER (
    STU_ID              CHAR(10)        NOT NULL,
    FIRST_NAME          VARCHAR(30)     NOT NULL,
    LAST_NAME           VARCHAR(30)     NOT NULL,
    DOB                 DATE            NOT NULL,
    GENDER              CHAR(1)         NOT NULL,
    DEPARTMENT          CHAR(4)         NOT NULL,
    YEAR_OF_STUDY       SMALLINT        NOT NULL,
    SEMESTER            SMALLINT        NOT NULL,
    EMAIL               VARCHAR(60)     NOT NULL,
    PHONE               CHAR(10)        NOT NULL,
    ENROLL_DATE         DATE            NOT NULL,
    STATUS              CHAR(1)         NOT NULL DEFAULT 'A',
    CREATED_TS          TIMESTAMP       NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_STUDENT_MASTER PRIMARY KEY (STU_ID),
    CONSTRAINT CK_STU_GENDER CHECK (GENDER IN ('M', 'F', 'O')),
    CONSTRAINT CK_STU_YEAR CHECK (YEAR_OF_STUDY BETWEEN 1 AND 4),
    CONSTRAINT CK_STU_STATUS CHECK (STATUS IN ('A', 'S', 'G'))
);

CREATE UNIQUE INDEX IX_STU_EMAIL ON STUDENT_MASTER (EMAIL);
CREATE INDEX IX_STU_DEPT ON STUDENT_MASTER (DEPARTMENT, YEAR_OF_STUDY);

-- 3. SCHOLARSHIP APPLICATION TABLE
CREATE TABLE SCHOLARSHIP_APPLICATION (
    APP_ID              CHAR(10)        NOT NULL,
    STU_ID              CHAR(10)        NOT NULL,
    SCH_CODE            CHAR(6)         NOT NULL,
    APP_DATE            DATE            NOT NULL,
    CGPA                DECIMAL(4,2)    NOT NULL,
    ATTENDANCE_PCT      DECIMAL(5,2)    NOT NULL,
    FAMILY_INCOME       DECIMAL(10,2)   NOT NULL,
    ACTIVE_ARREARS      SMALLINT        NOT NULL,
    BANK_AC_NUM         VARCHAR(18)     NOT NULL,
    BANK_IFSC           CHAR(11)        NOT NULL,
    STATUS              VARCHAR(12)     NOT NULL DEFAULT 'SUBMITTED',
    SUBMITTED_TS        TIMESTAMP       NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_SCH_APP PRIMARY KEY (APP_ID),
    CONSTRAINT FK_APP_STUDENT FOREIGN KEY (STU_ID) 
        REFERENCES STUDENT_MASTER (STU_ID) ON DELETE RESTRICT,
    CONSTRAINT FK_APP_SCHOLARSHIP FOREIGN KEY (SCH_CODE) 
        REFERENCES SCHOLARSHIP_MASTER (SCH_CODE) ON DELETE RESTRICT,
    CONSTRAINT CK_APP_STATUS CHECK (
        STATUS IN ('SUBMITTED', 'VALIDATED', 'DUPLICATE', 'PROCESSED', 'REJECTED')
    ),
    CONSTRAINT CK_APP_CGPA CHECK (CGPA BETWEEN 0.00 AND 10.00),
    CONSTRAINT CK_APP_ATTN CHECK (ATTENDANCE_PCT BETWEEN 0.00 AND 100.00)
);

CREATE INDEX IX_APP_STU_CYCLE ON SCHOLARSHIP_APPLICATION (STU_ID, SCH_CODE);
CREATE INDEX IX_APP_STATUS ON SCHOLARSHIP_APPLICATION (STATUS);

-- 4. ELIGIBILITY RESULT TABLE
CREATE TABLE ELIGIBILITY_RESULT (
    EVAL_ID             INTEGER         GENERATED ALWAYS AS IDENTITY,
    APP_ID              CHAR(10)        NOT NULL,
    STU_ID              CHAR(10)        NOT NULL,
    SCH_CODE            CHAR(6)         NOT NULL,
    CGPA                DECIMAL(4,2)    NOT NULL,
    ATTENDANCE_PCT      DECIMAL(5,2)    NOT NULL,
    FAMILY_INCOME       DECIMAL(10,2)   NOT NULL,
    ACTIVE_ARREARS      SMALLINT        NOT NULL,
    STATUS              CHAR(1)         NOT NULL,
    REASON_CODE         VARCHAR(10)     NOT NULL,
    AWARD_AMOUNT        DECIMAL(9,2)    NOT NULL DEFAULT 0.00,
    BATCH_ID            CHAR(10)        NOT NULL,
    PROCESSED_TS        TIMESTAMP       NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_ELIG_RESULT PRIMARY KEY (EVAL_ID),
    CONSTRAINT FK_ELIG_APP FOREIGN KEY (APP_ID) 
        REFERENCES SCHOLARSHIP_APPLICATION (APP_ID) ON DELETE CASCADE,
    CONSTRAINT CK_ELIG_STATUS CHECK (STATUS IN ('E', 'R', 'D', 'I'))
);

CREATE INDEX IX_ELIG_APP ON ELIGIBILITY_RESULT (APP_ID);
CREATE INDEX IX_ELIG_STATUS ON ELIGIBILITY_RESULT (STATUS);
CREATE INDEX IX_ELIG_BATCH ON ELIGIBILITY_RESULT (BATCH_ID);

-- 5. DISBURSEMENT RECORD TABLE
CREATE TABLE DISBURSEMENT_RECORD (
    DISB_REF_ID         CHAR(12)        NOT NULL,
    APP_ID              CHAR(10)        NOT NULL,
    STU_ID              CHAR(10)        NOT NULL,
    AMOUNT              DECIMAL(9,2)    NOT NULL,
    BANK_AC_NUM         VARCHAR(18)     NOT NULL,
    BANK_IFSC           CHAR(11)        NOT NULL,
    STATUS              VARCHAR(10)     NOT NULL DEFAULT 'PENDING',
    UTR_NUMBER          VARCHAR(16),
    BATCH_ID            CHAR(10)        NOT NULL,
    VALUE_DATE          DATE            NOT NULL,
    DISBURSED_TS        TIMESTAMP,
    CONSTRAINT PK_DISB_RECORD PRIMARY KEY (DISB_REF_ID),
    CONSTRAINT FK_DISB_APP FOREIGN KEY (APP_ID) 
        REFERENCES SCHOLARSHIP_APPLICATION (APP_ID) ON DELETE RESTRICT,
    CONSTRAINT CK_DISB_STATUS CHECK (STATUS IN ('PENDING', 'PROCESSED', 'FAILED', 'HOLD'))
);

CREATE UNIQUE INDEX IX_DISB_APP_UNIQUE ON DISBURSEMENT_RECORD (APP_ID);
CREATE INDEX IX_DISB_STATUS ON DISBURSEMENT_RECORD (STATUS);
CREATE INDEX IX_DISB_BATCH ON DISBURSEMENT_RECORD (BATCH_ID);

-- 6. PROCESSING AUDIT TABLE
CREATE TABLE PROCESSING_AUDIT (
    AUDIT_ID            INTEGER         GENERATED ALWAYS AS IDENTITY,
    BATCH_ID            CHAR(10)        NOT NULL,
    JOB_NAME            CHAR(8)         NOT NULL,
    RECS_READ           INTEGER         NOT NULL,
    RECS_VALID          INTEGER         NOT NULL,
    RECS_ELIGIBLE       INTEGER         NOT NULL,
    RECS_REJECTED       INTEGER         NOT NULL,
    RECS_DUPLICATE      INTEGER         NOT NULL,
    TOTAL_DISBURSED_AMT DECIMAL(12,2)   NOT NULL,
    RETURN_CODE         SMALLINT        NOT NULL,
    START_TS            TIMESTAMP       NOT NULL,
    END_TS              TIMESTAMP       NOT NULL,
    EXECUTED_BY         VARCHAR(16)     NOT NULL DEFAULT 'ZOSBATCH',
    CONSTRAINT PK_PROC_AUDIT PRIMARY KEY (AUDIT_ID)
);

CREATE INDEX IX_AUD_BATCH ON PROCESSING_AUDIT (BATCH_ID);
